namespace UsbRecoverySuite.Core.Services.Localization;

public class LocalizationService : ILocalizationService
{
    private static readonly string LanguageFilePath = Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
        "UsbRecoverySuite",
        "language.txt");

    private string _currentLanguage = LoadLanguage();
    public event PropertyChangedEventHandler? PropertyChanged;
    public event Action? LanguageChanged;

    public IReadOnlyList<string> AvailableLanguages => new[] { "ru", "en", "uk" };

    public string CurrentLanguage
    {
        get => _currentLanguage;
        set
        {
            if (_currentLanguage != value && (value == "ru" || value == "en" || value == "uk"))
            {
                _currentLanguage = value;
                SaveLanguage(value);
                OnPropertyChanged(string.Empty);
                OnPropertyChanged("Item[]");
                LanguageChanged?.Invoke();
            }
        }
    }

    private static string LoadLanguage()
    {
        try
        {
            var saved = File.ReadAllText(LanguageFilePath).Trim();
            return saved is "ru" or "en" or "uk" ? saved : "ru";
        }
        catch
        {
            return "ru";
        }
    }

    private static void SaveLanguage(string language)
    {
        try
        {
            Directory.CreateDirectory(Path.GetDirectoryName(LanguageFilePath)!);
            File.WriteAllText(LanguageFilePath, language);
        }
        catch
        {
            // Language selection still applies for this session when settings cannot be saved.
        }
    }

    public string this[string key] => Get(key);

    public string LocalizeSystemValue(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return value ?? string.Empty;

        var translated = _currentLanguage switch
        {
            "en" => "Standard disk drives",
            "uk" => "Стандартні дискові накопичувачі",
            _ => "Стандартные дисковые накопители"
        };
        var result = value;
        foreach (var source in new[]
                 {
                     "Standard disk drives", "Disk drives", "Стандартные дисковые накопители",
                     "Стандартный дисковый накопитель", "Дисковые накопители"
                 })
            result = result.Replace(source, translated, StringComparison.OrdinalIgnoreCase);

        return result;
    }

    public string LocalizePartitionType(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return value ?? string.Empty;

        var key = value.Trim().ToLowerInvariant() switch
        {
            "basic data partition" => "PartitionTypeBasic",
            "basic data partition (microsoft)" => "PartitionTypeBasicMicrosoft",
            "efi system partition (esp)" => "PartitionTypeEfi",
            "windows recovery partition" => "PartitionTypeRecovery",
            "microsoft reserved (msr)" => "PartitionTypeReserved",
            "windows ldm data" => "PartitionTypeLdmData",
            "windows ldm metadata" => "PartitionTypeLdmMetadata",
            _ => null
        };
        return key == null ? LocalizeSystemValue(value) : Get(key);
    }

    public string Get(string key, params object[] args)
    {
        var dict = _currentLanguage switch
        {
            "en" => EnStrings,
            "uk" => UkStrings,
            _ => RuStrings
        };
        if (!dict.TryGetValue(key, out var text))
        {
            if (!EnStrings.TryGetValue(key, out text))
            {
                text = key;
            }
        }

        if (args != null && args.Length > 0)
        {
            try
            {
                return string.Format(text, args);
            }
            catch
            {
                return text;
            }
        }

        return text;
    }

    protected void OnPropertyChanged([CallerMemberName] string? name = null)
    {
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(name));
    }

